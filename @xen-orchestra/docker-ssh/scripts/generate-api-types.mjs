#!/usr/bin/env node
// Generates `src/docker-api.gen.mts`: the TypeScript types of the Docker Engine
// API definitions this package reads, from the official OpenAPI (Swagger 2.0)
// specifications published by Docker.
//
// - API 1.44 (`MAX_API_VERSION` in `src/connection.mts`) for everything
// - API 1.48 for the stats: before it, the spec documents the stats response as
//   a plain `object` (the field names did not change, `ContainerStatsResponse`
//   only documents them)
//
// Only the definitions reachable from `ROOTS` are kept. The inspect response is
// inline in the 1.44 spec: it is added as `ContainerInspectResponse`, the name
// later specs use.
//
//   yarn generate-api-types    # needs network access (specs + npx)

import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { parse } from 'yaml'

const SPEC_URL = version => `https://docs.docker.com/reference/api/engine/version/v${version}.yaml`
const API_VERSION = '1.44'
const STATS_API_VERSION = '1.48'
const OPENAPI_TYPESCRIPT = 'openapi-typescript@5.4.2' // last major reading Swagger 2.0

const ROOTS = [
  'SystemVersion',
  'SystemInfo',
  'ContainerSummary',
  'ContainerInspectResponse',
  'ContainerConfig',
  'ContainerState',
  'Health',
  'HealthcheckResult',
  'Port',
  'EndpointSettings',
  'MountPoint',
  'RestartPolicy',
]
const STATS_ROOTS = ['ContainerStatsResponse']

async function fetchSpec(version) {
  const response = await fetch(SPEC_URL(version))
  if (!response.ok) {
    throw new Error(`${SPEC_URL(version)}: ${response.status}`)
  }
  return parse(await response.text())
}

function getResponseSchema(spec, path) {
  const { responses } = spec.paths[path].get
  return (responses[200] ?? responses['200']).schema
}

// definitions reachable from `roots`, following every `$ref`
function pickDefinitions(definitions, roots) {
  const picked = {}
  const visit = value => {
    if (Array.isArray(value)) {
      value.forEach(visit)
    } else if (value !== null && typeof value === 'object') {
      for (const [key, child] of Object.entries(value)) {
        if (key === '$ref' && typeof child === 'string') {
          add(child.slice('#/definitions/'.length))
        } else {
          visit(child)
        }
      }
    }
  }
  const add = name => {
    if (picked[name] === undefined) {
      if (definitions[name] === undefined) {
        throw new Error(`missing definition ${name}`)
      }
      picked[name] = definitions[name]
      visit(definitions[name])
    }
  }
  roots.forEach(add)
  return picked
}

const spec = await fetchSpec(API_VERSION)
const statsSpec = await fetchSpec(STATS_API_VERSION)

const definitions = pickDefinitions(
  { ...spec.definitions, ContainerInspectResponse: getResponseSchema(spec, '/containers/{id}/json') },
  ROOTS
)
const statsDefinitions = pickDefinitions(statsSpec.definitions, STATS_ROOTS)
for (const name of Object.keys(statsDefinitions)) {
  if (definitions[name] !== undefined) {
    throw new Error(`${name} is in both specs`)
  }
}

const dir = mkdtempSync(join(tmpdir(), 'docker-api-types-'))
try {
  const input = join(dir, 'spec.json')
  const output = join(dir, 'types.ts')
  writeFileSync(
    input,
    JSON.stringify({
      swagger: '2.0',
      info: { title: 'Docker Engine API (subset)', version: API_VERSION },
      paths: {},
      definitions: { ...definitions, ...statsDefinitions },
    })
  )
  execFileSync('npx', ['--yes', OPENAPI_TYPESCRIPT, input, '--output', output], { stdio: 'inherit' })
  const types = readFileSync(output, 'utf8')
    // no paths, no operations: only `definitions` is useful
    .replace(/^export interface paths \{\}\n\n/m, '')
    .replace(/^export interface operations \{\}\n\n/m, '')
    .replace(/^export interface external \{\}\n?/m, '')

  const target = new URL('../src/docker-api.gen.mts', import.meta.url)
  writeFileSync(
    target,
    `// Generated by scripts/generate-api-types.mjs, do not edit.
//
// Docker Engine API ${API_VERSION} definitions read by this package (and the stats
// definitions of API ${STATS_API_VERSION}), from the official specifications:
// ${SPEC_URL(API_VERSION)}
// ${SPEC_URL(STATS_API_VERSION)}
//
// These are what the daemon is documented to send, they are not checked at
// runtime: see \`wire.mts\` for how this package uses them.

${types.trim()}
`
  )
  execFileSync('npx', ['prettier', '--write', target.pathname], { stdio: 'inherit' })
  console.log('definitions:', Object.keys(definitions).length + Object.keys(statsDefinitions).length)
} finally {
  rmSync(dir, { recursive: true, force: true })
}
